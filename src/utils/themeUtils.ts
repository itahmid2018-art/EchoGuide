export type ThemeMode = 'auto' | 'day' | 'night';

export interface TimeOfDayInfo {
  isDay: boolean;
  isSunset: boolean;
  hour: number;
  formattedTime: string;
  themeTitle: string;
}

export function getTimeOfDayInfo(): TimeOfDayInfo {
  const now = new Date();
  const hour = now.getHours();

  // Daytime (Light mode): 6:00 AM to 5:59 PM
  // Sunset / Twilight (Dark mode): 6:00 PM to 8:59 PM
  // Night (Dark mode): 9:00 PM to 5:59 AM
  const isDay = hour >= 6 && hour < 18;
  const isSunset = hour >= 18 && hour < 21;

  let themeTitle = 'Daytime Tour';
  if (isSunset) {
    themeTitle = 'Sunset / Twilight Tour';
  } else if (!isDay) {
    themeTitle = 'Night Lights Tour';
  }

  const formattedTime = now.toLocaleTimeString([], {
    hour: 'numeric',
    minute: '2-digit',
  });

  return {
    isDay,
    isSunset,
    hour,
    formattedTime,
    themeTitle,
  };
}

